create table if not exists public.payment_orders (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  project_id uuid not null references public.projects(id) on delete cascade,
  provider text not null check (provider in ('click','payme')),
  plan_slug text not null references public.payment_plans(slug),
  amount_uzs integer not null check (amount_uzs > 0),
  amount_tiyin bigint not null check (amount_tiyin > 0),
  status text not null default 'pending' check (status in ('pending','paid','cancelled','failed','expired','refunded')),
  publish_slug text not null check (publish_slug ~ '^[a-z0-9][a-z0-9-]{3,55}$'),
  template_slug text not null,
  public_content jsonb not null default '{}'::jsonb,
  provider_transaction_id text,
  provider_state integer,
  provider_reason integer,
  provider_created_ms bigint,
  provider_performed_ms bigint,
  provider_cancelled_ms bigint,
  provider_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '12 hours'),
  paid_at timestamptz,
  cancelled_at timestamptz
);
alter table public.payment_orders enable row level security;
create index if not exists payment_orders_owner_created_idx on public.payment_orders(owner_id, created_at desc);
create index if not exists payment_orders_project_status_idx on public.payment_orders(project_id, status);
create unique index if not exists payment_orders_provider_tx_uidx on public.payment_orders(provider, provider_transaction_id) where provider_transaction_id is not null;
create unique index if not exists payment_orders_one_paid_project_uidx on public.payment_orders(project_id) where status='paid';
drop policy if exists "payment orders owner read" on public.payment_orders;
create policy "payment orders owner read" on public.payment_orders for select to authenticated using ((select auth.uid()) = owner_id);
grant select on public.payment_orders to authenticated;
revoke insert, update, delete on public.payment_orders from anon, authenticated;

create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.payment_orders(id) on delete cascade,
  provider text not null,
  event_type text not null,
  provider_transaction_id text,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.payment_events enable row level security;
revoke all on public.payment_events from anon, authenticated;
create index if not exists payment_events_order_created_idx on public.payment_events(order_id, created_at);

