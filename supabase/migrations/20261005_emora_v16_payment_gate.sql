create or replace function public.emora_finalize_paid_order(
  p_order_id uuid,
  p_provider_transaction_id text,
  p_provider_payload jsonb default '{}'::jsonb
) returns table(project_id uuid, slug text)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  o public.payment_orders%rowtype;
begin
  select * into o from public.payment_orders where id=p_order_id for update;
  if not found then raise exception 'Payment order not found'; end if;
  if o.status='paid' then
    if o.provider_transaction_id is distinct from p_provider_transaction_id then raise exception 'Payment transaction mismatch'; end if;
    return query select o.project_id,o.publish_slug;
    return;
  end if;
  if o.status<>'pending' then raise exception 'Payment order is not pending'; end if;
  if o.expires_at < now() then
    update public.payment_orders set status='expired',updated_at=now() where id=o.id;
    raise exception 'Payment order expired';
  end if;
  if exists(select 1 from public.payment_orders x where x.provider=o.provider and x.provider_transaction_id=p_provider_transaction_id and x.id<>o.id) then raise exception 'Provider transaction already used'; end if;
  update public.payment_orders
    set status='paid',provider_transaction_id=p_provider_transaction_id,
        provider_state=coalesce(provider_state,2),provider_payload=coalesce(p_provider_payload,'{}'::jsonb),
        paid_at=coalesce(paid_at,now()),updated_at=now()
    where id=o.id;
  insert into public.published_sites(project_id,slug,template_slug,public_content,is_active,published_at,updated_at)
    values(o.project_id,o.publish_slug,o.template_slug,o.public_content,true,now(),now())
  on conflict (project_id) do update set
    slug=excluded.slug,template_slug=excluded.template_slug,public_content=excluded.public_content,
    is_active=true,published_at=now(),updated_at=now();
  update public.projects set status='published',slug=o.publish_slug,published_at=now(),updated_at=now() where id=o.project_id;
  insert into public.payment_events(order_id,provider,event_type,provider_transaction_id,payload)
    values(o.id,o.provider,'paid',p_provider_transaction_id,coalesce(p_provider_payload,'{}'::jsonb));
  return query select o.project_id,o.publish_slug;
end $function$;
revoke all on function public.emora_finalize_paid_order(uuid,text,jsonb) from public, anon, authenticated;
grant execute on function public.emora_finalize_paid_order(uuid,text,jsonb) to service_role;

create or replace function public.emora_unpublish_project(p_project uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if (select auth.uid()) is null then raise exception 'Login required'; end if;
  if not exists(select 1 from public.projects p where p.id=p_project and p.owner_id=(select auth.uid())) then raise exception 'Project not found'; end if;
  update public.published_sites set is_active=false,updated_at=now() where project_id=p_project;
  if not found then raise exception 'No published site owned by this user'; end if;
  update public.projects set status='draft',updated_at=now() where id=p_project and owner_id=(select auth.uid());
  return true;
end $function$;
revoke all on function public.emora_unpublish_project(uuid) from public, anon;
grant execute on function public.emora_unpublish_project(uuid) to authenticated;
